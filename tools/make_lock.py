"""Write requirements-lock.txt with the exact versions used in the reported run.

Reads results/environment/pip_freeze.txt (captured by scripts/colab_pipeline.py on the training machine)
and keeps the packages PixelTrace imports plus their key runtime dependencies.

    python tools/make_lock.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KEEP = ["torch", "torchvision", "timm", "numpy", "pandas", "pillow", "scikit-learn", "scipy", "matplotlib",
        "pyyaml", "onnx", "onnxruntime", "gdown", "huggingface-hub", "safetensors"]

freeze = (ROOT / "results" / "environment" / "pip_freeze.txt").read_text(encoding="utf-8").splitlines()
found = {}
for line in freeze:
    m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line.strip())
    if m and m.group(1).lower().replace("_", "-") in KEEP:
        found[m.group(1).lower().replace("_", "-")] = m.group(2)
missing = [k for k in KEEP if k not in found]
dep = json.loads((ROOT / "results" / "deployment.json").read_text(encoding="utf-8"))
env = json.loads((ROOT / "results" / "runs" / dep["run"] / "environment.json").read_text(encoding="utf-8"))
header = [
    "# Exact versions from the reported PixelTrace run (generated by tools/make_lock.py).",
    f"# Python {env['python']} | {env.get('gpu', 'CPU')} | CUDA {env.get('torch_cuda')} | {env['platform']}",
    "# torch/torchvision versions carry a CUDA suffix on the training machine; install the matching build",
    "# for your platform from https://pytorch.org if pip cannot resolve it.",
]
lines = header + [f"{k}=={found[k]}" for k in KEEP if k in found]
(ROOT / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines))
if missing:
    print("not in freeze (ok if unused):", missing)
